'use strict';
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const base=JSON.parse(fs.readFileSync(path.join(root,'content/base.json'),'utf8'));
const packs=fs.readdirSync(path.join(root,'content')).filter(n=>n.endsWith('.pack.cjs')).sort().map(n=>require(path.join(root,'content',n)));
const data={...base,quizzes:base.quizzes||[],resources:base.resources||[]};
for(const pack of packs) {
  if(pack.worlds)data.worlds.push(...pack.worlds);
  if(pack.sources)data.resources.push(...pack.sources);
  for(const key of ['lessons','exercises','quizzes','writingChallenges'])data[key].push(...(pack[key]||[]));
}
for(const key of ['worlds','lessons','exercises','quizzes','writingChallenges']) {
  const ids=data[key].map(x=>x.id);if(new Set(ids).size!==ids.length)throw new Error('Duplicate ID in '+key);
}
fs.writeFileSync(path.join(root,'data.js'),'// Generated by node tools/compile-content.cjs. Edit content/ sources; keep IDs stable.\nwindow.LEARNING_DATA = '+JSON.stringify(data,null,2)+';\n');
console.log(JSON.stringify(Object.fromEntries(Object.entries(data).filter(([,v])=>Array.isArray(v)).map(([k,v])=>[k,v.length]))));
const lines=['# 课程与题库目录','',`共 ${data.worlds.length} 个世界、${data.lessons.length} 个知识点、${data.exercises.length} 道拼装、${data.quizzes.length} 道知识测验、${data.writingChallenges.length} 道自主造句。`,'','覆盖常用词法、句法及听说读写学习框架，不等同于收录全部词汇、所有语言现象或完整等级教材。所有知识点均有对应练习；实际发音与听力仍需真实材料和口头训练。',''];
for(const w of data.worlds){lines.push(`## ${w.title}`,'',w.description,'','| 知识点 | 难度 | 拼装 | 测验 | 造句 |','| --- | --- | ---: | ---: | ---: |');for(const l of data.lessons.filter(x=>x.world===w.id))lines.push(`| ${l.title.replaceAll('|','/')} | ${l.level} | ${data.exercises.filter(t=>t.lessonId===l.id).length} | ${data.quizzes.filter(t=>t.lessonId===l.id).length} | ${data.writingChallenges.filter(t=>t.lessonId===l.id).length} |`);lines.push('');}
fs.writeFileSync(path.join(root,'CURRICULUM.md'),lines.join('\n')+'\n');
